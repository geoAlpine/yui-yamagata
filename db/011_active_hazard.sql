-- 「いまどの災害か」を保持する（2026-08-05）
--
-- 実データを入れて分かったこと:
--   山形駅から近い順50件のうち緊急避難場所は16件。洪水に対応するのは5件だけ。
--   さらに「山形西高等学校（体育館）」は洪水対応だが
--       「山形西高等学校（グラウンド）」は地震のみ。同じ学校で50m差。
--   豪雨のときにグラウンドへ逃げたら水が来る。
--
-- カードに種別を出すだけでは読み飛ばされる。名前がほぼ同じで距離も近いため。
-- 運営者は災害モードに切り替えるとき「いまどの災害か」を知っているので、
-- そこで一度指定してもらい、対応しない避難場所は既定で出さない。
-- 被災地で利用者に絞り込み操作をさせるより確実。
ALTER TABLE site_state ADD COLUMN IF NOT EXISTS hazard text;
COMMENT ON COLUMN site_state.hazard IS
  'いま起きている災害の種別。flood/landslide/earthquake/tsunami など。'
  'NULL なら絞り込まない（種別が定まらない・複合災害のとき）';
