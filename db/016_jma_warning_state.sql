-- 警報通知の重複を止める（2026-08-12）
--
-- ── 何が起きたか ──
-- 2026-08-07 14:52 〜 08-08 17:00 の大雨警報で、45通のメールが届いた。
-- 警報はその間ずっと継続していた。新しい災害が45回起きたわけではない。
--
-- 原因は重複判定の単位を「気象庁の文書URL」にしていたこと。掛かっていたのは2つ。
--
--   1. 気象庁は同じ発表を3つの形式で配信する
--        VPWW53 気象特別警報・警報・注意報        → Kind名「大雨警報」
--        VPWW54 気象警報・注意報（Ｈ２７）         → Kind名「大雨警報」
--        VPWW5x 気象警報・注意報（Ｒ０６）（大雨）  → Kind名「レベル３大雨警報」
--      3つとも別URLなので、1回の発表で必ず3通になる。
--      ログに 大雨警報／大雨警報／レベル３大雨警報 が三つ組で並ぶのはこれ。
--
--   2. 文書は県内全市町村の発表状況の一覧で、県内のどこかで何かが変わるたび
--      新しいURLで出し直される。大雨と無関係な変化（ある町に雷注意報が出た等）
--      でも出し直されるため、継続中の大雨警報が何度も「新着」になる。
--      実際 13:37 の2分後の 13:39 にまた3通来ている。
--
--   3通 × 17回の再発表 = 45通。
--
-- ── どう変えるか ──
-- 文書ではなく「いま出ている警報の種別」を単位にする。
-- 同じ種別が続いている間は鳴らさない。種別が増えたときだけ鳴らす。
-- 45通は最初の1通だけになり、洪水警報が加わればその時点で1通鳴る。
--
-- 名称は正規化してから入れる。「レベル３大雨警報」と「大雨警報」を
-- 別物として扱うと、3通が2通に減るだけで終わる。
--
-- ── 消えたことは判定しない ──
-- Ｒ０６形式は警報種別ごとに分かれた部分的な文書で、大雨の文書には
-- 暴風のことは書いていない。「この文書に無いから解除された」と見なすと、
-- 暴風の文書を1つ処理しただけで大雨警報が消えたことになり、次の発表で
-- また鳴り出す。だから行は消さず、last_seen が古いかどうかだけを見る。
--
-- 自動切替（震度5弱以上・特別警報）には手を入れない。
-- あちらは鳴りすぎるより鳴らないほうが致命的で、非対称にしてある。

CREATE TABLE IF NOT EXISTS jma_warning_state (
  -- 正規化した警報名。「レベル３大雨警報」→「大雨警報」
  kind        text PRIMARY KEY,
  first_seen  timestamptz NOT NULL DEFAULT now(),
  -- 最後にこの警報を気象庁の発表の中に見た時刻。
  -- 発表のたびに更新する。これが古いことが「収まった」の唯一の根拠
  last_seen   timestamptz NOT NULL DEFAULT now(),
  -- 最後にメールを送った時刻。NULL なら一度も送っていない
  notified_at timestamptz
);

COMMENT ON TABLE jma_warning_state IS
  '通知対象の警報が今出ているか。同じ警報の再発表でメールを繰り返さないために持つ';

CREATE INDEX IF NOT EXISTS jma_warning_state_last_seen_idx ON jma_warning_state (last_seen);
